/** Все враги указанной расы (из ENEMY_TYPES), для примеров в каталоге рас. */
export function getEnemiesByRace(raceId) {
  return ENEMY_TYPES.filter((e) => e.race === raceId);
}

export function getRaceById(id) {
  return RACES.find((r) => r.id === id) || null;
}